def test_deny_envelopes_match_the_go_renderings_byte_for_byte() -> None:
    reason = (
        "BLOCKED: the session guard did not complete (host-unavailable) and this call names a session-ending "
        "program, so it stays denied (AGENTS.md § Protect Existing Sessions). Retry once the Captain Hook host "
        "answers, or ask the owner to run it."
    )
    assert guard.deny_envelope("PreToolUse", "host-unavailable") == (
        '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny",'
        f'"permissionDecisionReason":"{reason}"}}}}'
    )
    assert guard.deny_envelope("PermissionRequest", "host-unavailable") == (
        f'{{"hookSpecificOutput":{{"decision":{{"behavior":"deny","message":"{reason}"}},'
        '"hookEventName":"PermissionRequest"}}'
    )
    for kind in guard.KINDS:
        envelope = json.loads(guard.deny_envelope("PreToolUse", kind))
        assert f"({kind})" in envelope["hookSpecificOutput"]["permissionDecisionReason"]
    with pytest.raises(ValueError, match="guessed"):
        guard.deny_envelope("PreToolUse", "guessed")
