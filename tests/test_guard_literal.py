def test_every_folded_spelling_of_every_guarded_name_matches_as_the_parent_did() -> None:
    spellings = [
        f"{name[:index]}{source}{name[index + 1 :]} -9 1"
        for name in guarded_names()
        for index, letter in enumerate(name)
        for source, target in guard.FOLDS.items()
        if target == letter
    ]
    assert len(spellings) > 40
    for text in spellings:
        assert parent_names_guarded(text), text
        assert guard.names_guarded(text), text


def guard_rows() -> list[tuple[Any, object]]:
    _state.hooks.clear()
    importlib.reload(sessions)
    guards = [hook for hook in _state.hooks if hook.spec.mandatory]
    assert len(guards) == len(_state.hooks) > 1
    assert all(hook.spec.tests for hook in guards)
    return [
        (key, expected)
        for hook in guards
        for key, expected in (hook.spec.tests or {}).items()
        if not isinstance(key, str)
    ]


def test_stop_tools_are_the_stop_guards_names_and_flag_exactly_the_rows_it_blocks() -> None:
    _state.hooks.clear()
    importlib.reload(stops)
    assert set(DEFINITION["tools"]) == set(stops.STOP_TOOLS)
    [stop_guard] = _state.hooks
    assert stop_guard.spec.mandatory
    rows = [(row, expected) for row, expected in (stop_guard.spec.tests or {}).items() if not isinstance(row, str)]
    assert len(rows) > 8
    for row, expected in rows:
        for event in (Event.PreToolUse, Event.PermissionRequest):
            raw = json.dumps(input_to_event(event, row)._raw).encode()
            assert guard.mandatory(event.name, raw) is isinstance(expected, Block), (event, row)


def test_every_inline_guard_row_the_prefilter_matches_is_mandatory_or_allowed() -> None:
    rows = guard_rows()
    matched = 0
    for row, expected in rows:
        evt = input_to_event(Event.PreToolUse, row)
        raw = json.dumps(evt._raw).encode()
        if session_guard.names_a_guarded_program(evt):
            matched += 1
            assert guard.mandatory("PreToolUse", raw) or isinstance(expected, Allow), row
            assert guard.mandatory("PermissionRequest", raw) == guard.mandatory("PreToolUse", raw), row
    assert matched > 40


