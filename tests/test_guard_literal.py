def shell_value(name: str) -> str:
    return subprocess.run(
        ["/bin/bash", "-c", f'. "$1"; printf %s "${name}"', "guard", str(SHELL_LITERAL)],
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def test_shell_rendering_carries_the_pass_exit_and_the_static_envelopes() -> None:
    lines = SHELL_LITERAL.read_text().splitlines()
    assert lines[0].startswith("# GENERATED by `uv run python hatch_build.py`")
    assert [line.partition("=")[0] for line in lines[1:]] == [
        "GUARD_PASS_EXIT",
        *(f"GUARD_DENY_{event}" for event in DEFINITION["events"]),
    ]
    assert shell_value("GUARD_PASS_EXIT") == str(guard.PASS_EXIT)
    for event in DEFINITION["events"]:
        assert shell_value(f"GUARD_DENY_{event}") == guard.deny_envelope(event, STATIC_DENY_KIND)


